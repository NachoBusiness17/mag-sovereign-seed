import hashlib
import json
import sys
from datetime import datetime, timezone
from pathlib import Path
from typing import Optional

ROOT = Path(__file__).resolve().parent.parent
TIP_FILE = ROOT / "memory" / "biography" / "verkle_tip.json"

from mag.audit_log import audit_log  # noqa: E402
from mag.constants import SPORE_SEED_FILE  # noqa: E402


def _chain_tip() -> Optional[dict]:
    """Read the current verkle tip (root hash anchor). None if absent/corrupt."""
    if not TIP_FILE.is_file():
        return None
    try:
        return json.loads(TIP_FILE.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return None


def generate_spore_seed(seat_id: str, root_hash: str, timestamp: Optional[str] = None) -> str:
    """Create a cryptographically unique spore seed anchored to a verkle chain root.

    The seed binds the seat identity to a specific chain state, creating a continuity
    anchor that survives process restarts and substrate changes.

    Args:
        seat_id: Unique identifier of the seat (e.g., "zcode")
        root_hash: Current verkle chain root hash
        timestamp: ISO timestamp (autogenerated if None)

    Returns:
        Hex digest of the spore seed
    """
    if timestamp is None:
        timestamp = datetime.now(timezone.utc).isoformat()

    # Combine seat ID, timestamp, and chain root into a canonical string
    seed_material = f"{seat_id}:{timestamp}:{root_hash}"

    # Create SHA256 hash as the spore seed
    seed = hashlib.sha256(seed_material.encode()).hexdigest()

    # Append to spore seed log (append-only); the record carries the timestamp so
    # validate_spore_seed can reconstruct the exact material.
    _append_seed_record({
        "timestamp": timestamp,
        "seed": seed,
        "seat_id": seat_id,
        "root_hash": root_hash,
    })

    audit_log("spore_seed_generated", {
        "seat_id": seat_id,
        "seed": seed,
        "root_hash": root_hash,
    })

    return seed


def validate_spore_seed(seed: str, seat_id: str, root_hash: str, timestamp: str) -> bool:
    """Verify that a spore seed matches its claimed components.

    Falsifiable check: given the seed and the exact components (including the
    timestamp generate used), the relationship is deterministically re-derivable.

    Returns:
        True if the seed is cryptographically valid, False otherwise
    """
    material = f"{seat_id}:{timestamp}:{root_hash}"
    expected_seed = hashlib.sha256(material.encode()).hexdigest()
    return seed == expected_seed


def _seed_file(seat_id: str) -> Path:
    # SPORE_SEED_FILE is a Path template; str-roundtrip keeps constants.py canonical.
    return ROOT / Path(str(SPORE_SEED_FILE).format(seat_id=seat_id))


def _append_seed_record(record: dict) -> None:
    """Append a spore seed record to the append-only log file (JSON lines)."""
    seed_file = _seed_file(record["seat_id"])
    seed_file.parent.mkdir(parents=True, exist_ok=True)
    with open(seed_file, "a", encoding="utf-8") as f:
        f.write(json.dumps(record) + "\n")


def verify_seat_continuity(seat_id: str, min_sequence: int = 10) -> dict:
    """Verify that seat continuity is maintained across the seed chain.

    Returns:
        Dictionary with verification results
    """
    seed_file = _seed_file(seat_id)

    if not seed_file.exists():
        return {"valid": False, "error": f"No seed file found for seat {seat_id}"}

    with open(seed_file, "r", encoding="utf-8") as f:
        lines = f.readlines()

    valid_count = 0
    last_root = None

    for i, line in enumerate(lines):
        try:
            record = json.loads(line)
            seed = record["seed"]
            rec_seat_id = record["seat_id"]
            root_hash = record["root_hash"]
            timestamp = record["timestamp"]

            if rec_seat_id != seat_id:
                return {"valid": False, "error": f"Seat ID mismatch at line {i+1}: {rec_seat_id} != {seat_id}"}

            if not validate_spore_seed(seed, seat_id, root_hash, timestamp):
                return {"valid": False, "error": f"Invalid seed at line {i+1}"}

            # Check that chain roots progress consistently
            if last_root and root_hash == last_root:
                return {"valid": False, "error": f"Chain root repeated at line {i+1}"}

            last_root = root_hash
            valid_count += 1

            if valid_count >= min_sequence:
                break
        except (KeyError, ValueError) as e:
            return {"valid": False, "error": f"Parse error at line {i+1}: {str(e)}"}

    if valid_count < min_sequence:
        return {"valid": False, "error": f"Only {valid_count} valid seeds found (need {min_sequence})"}

    return {"valid": True, "seed_count": len(lines), "consecutive_valid": valid_count}


if __name__ == "__main__":
    import argparse

    parser = argparse.ArgumentParser(description="Spore Seed Manager")
    subparsers = parser.add_subparsers(dest="command", help="Command")

    # Generate command
    gen_parser = subparsers.add_parser("generate", help="Generate a new spore seed")
    gen_parser.add_argument("--seat", required=True, help="Seat identifier")
    gen_parser.add_argument("--root", help="Verkle chain root hash (optional, uses current tip)")

    # Verify command
    ver_parser = subparsers.add_parser("verify", help="Verify seat continuity")
    ver_parser.add_argument("--seat", required=True, help="Seat identifier")
    ver_parser.add_argument("--min", type=int, default=10, help="Minimum consecutive seeds")

    args = parser.parse_args()

    if args.command == "generate":
        tip = _chain_tip()
        root = args.root or (tip or {}).get("root")
        if not root:
            print("CONTINUITY FAILURE: no verkle tip found and no --root given", file=sys.stderr)
            sys.exit(1)
        seed = generate_spore_seed(args.seat, root)
        print(f"Generated spore seed for seat {args.seat}: {seed}")

    elif args.command == "verify":
        result = verify_seat_continuity(args.seat, args.min)
        if result["valid"]:
            print(f"Seat {args.seat} continuity verified: {result['seed_count']} seeds, {result['consecutive_valid']} consecutive valid")
        else:
            print(f"CONTINUITY FAILURE: {result['error']}")
            sys.exit(1)

    else:
        parser.print_help()
