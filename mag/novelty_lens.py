def _tokens(text: str) -> set[str]:
    return {t for t in _TOKEN_RE.findall((text or "").lower()) if t not in _STOP and len(t) > 2}


def _corpus() -> list[str]:
    """The classified research corpus: research_class registry signals + percolator invariants."""
    texts: list[str] = []
    try:
        from mag import research_class as rc
        for r in rc.lens_read(_full=True):
            if r.get("signal"):
                texts.append(r["signal"])
    except Exception:
        pass
    try:
        from mag import percolator as pc
        reg = pc._load_registry()
        for inv in (reg.get("invariants") or {}).values():
            if inv.get("text"):
                texts.append(inv["text"])
    except Exception:
        pass
    return texts


def novelty(text: str, *, corpus: list[str] | None = None, smooth: float = 0.05) -> dict[str, Any]:
    """Measure the level of novelty of a new steal/research item vs the classified corpus.

    novelty = (unseen significant tokens) / (all significant tokens), smoothed. A brand-new lens
    scores ~1.0; a near-repeat scores ~0. Verdict: novel | variant | repeat. Deterministic + $0.
    """
    tokens = _tokens(text)
    if not tokens:
        return {"ok": True, "schema": SCHEMA, "novelty": 0.0, "n_tokens": 0, "verdict": "repeat"}
    corpus = corpus if corpus is not None else _corpus()
    seen: set[str] = set()
    for c in corpus:
        seen |= _tokens(c)
    unseen = tokens - seen
    score = (len(unseen) + smooth) / (len(tokens) + smooth)
    verdict = "novel" if score >= 0.6 else ("variant" if score >= 0.25 else "repeat")
    return {"ok": True, "schema": SCHEMA, "novelty": round(score, 4),
            "n_tokens": len(tokens), "n_unseen": len(unseen), "n_overlap": len(tokens & seen),
            "verdict": verdict, "corpus_size": len(corpus), "unseen": sorted(unseen)[:12]}


def keyword_lens(keyword: str) -> dict[str, Any]:
    """Map ANY user keyword to its closest lens (domain+kind) + similar systems. Deterministic."""
    kw = (keyword or "").strip().lower()
    if kw in _KEYWORD_LENS:
        e = _KEYWORD_LENS[kw]
        return {"ok": True, "schema": SCHEMA, "keyword": kw, "lens": e["domain"],
                "kind": e["kind"], "similar_systems": e["systems"]}
    # fall back to research_class lexicons for the closest lens
    try:
        from mag import research_class as rc
        blob = kw
        domain = next((d for d, hs in rc._DOMAIN_HINT.items() if any(h in blob for h in hs)), "general")
        kind = next((k for k, hs in rc._KIND_HINT.items() if any(h in blob for h in hs)), "synthesis")
        return {"ok": True, "schema": SCHEMA, "keyword": kw, "lens": domain, "kind": kind,
                "similar_systems": rc._MIRROR.get(domain, [])}
    except Exception:
        return {"ok": True, "schema": SCHEMA, "keyword": kw, "lens": "general",
                "kind": "synthesis", "similar_systems": []}


def lens_map(keywords: list[str]) -> dict[str, Any]:
    """Build a keyword -> lens -> related-systems index (every keyword maps to similar systems)."""
    rows = []
    for k in keywords:
        if not (k or "").strip():
            continue
        n = novelty(k)
        kl = keyword_lens(k)
        rows.append({"keyword": k, "novelty": n["novelty"], "verdict": n["verdict"],
                     "lens": kl["lens"], "kind": kl["kind"], "similar_systems": kl["similar_systems"]})
    return {"ok": True, "schema": SCHEMA, "n_keywords": len(rows), "rows": rows}


